def jitter(base, pct=0.08):
    """기준가 ±pct 랜덤 변동"""
    delta = base * pct * (random.random() * 2 - 1)
    return round(base + delta, -3)  # 1,000원 단위 반올림


def random_date(days_back_max=730):
    """최근 2년 내 랜덤 날짜"""
    offset = random.randint(7, days_back_max)
    return date.today() - timedelta(days=offset)


def main():
    materials = {
        (m.ks_grade, m.diameter): m
        for m in Material.objects.filter(ks_code="KS D 3504")
    }
    if not materials:
        print("ERROR: 자재 데이터가 없습니다. 먼저 seed_data.py를 실행하세요.")
        return

    created_suppliers = 0
    created_histories = 0
    skipped = 0

    for biz_no, name, address, lat, lng in RAW_SUPPLIERS:
        lat_noise = (random.random() - 0.5) * 0.02  # ±0.01도 (약 ±1km)
        lng_noise = (random.random() - 0.5) * 0.02

        supplier, created = Supplier.objects.update_or_create(
            business_no=biz_no,
            defaults={
                "name":      name,
                "address":   address,
                "latitude":  Decimal(str(round(lat + lat_noise, 6))),
                "longitude": Decimal(str(round(lng + lng_noise, 6))),
                "source":    "manual",
            },
        )
        if created:
            created_suppliers += 1
            print(f"  공급사 생성: {name}")
        else:
            skipped += 1

        # 각 공급사 × 전체 자재에 대해 납품 이력 2~5건 생성
        for (grade, diam), material in materials.items():
            base = BASE_PRICES.get((grade, diam), 700000)
            n_histories = random.randint(2, 5)
            for _ in range(n_histories):
                price = jitter(base)
                qty   = random.choice([5000, 8000, 10000, 12000, 15000, 20000])
                SupplyHistory.objects.create(
                    supplier=supplier,
                    material=material,
                    contract_date=random_date(),
                    unit_price=price,
                    quantity=qty,
                    raw_data={"source": "PaceFlow seed", "grade": grade, "diameter": diam},
                )
                created_histories += 1

    print()
    print(f"완료:")
    print(f"  공급사 생성: {created_suppliers}개 / 기존 업데이트: {skipped}개")
    print(f"  납품 이력 생성: {created_histories}건")
    print(f"  전체 공급사 수: {Supplier.objects.count()}개")
    print(f"  좌표 있는 공급사: {Supplier.objects.exclude(latitude=None).count()}개")


if __name__ == "__main__":
    main()
